// Helper to compute yield metrics and detector results dynamically
export function calculateLotAnalysis(lot, allLots = BENCHMARK_LOTS, minDropPp = 5.0) {
  const references = allLots.filter(
    (other) => other.lot_id !== lot.lot_id && other.product_id === lot.product_id
  );
  if (!references.length) {
    return {
      lot_id: lot.lot_id,
      product_id: lot.product_id,
      status: "INSUFFICIENT_DATA",
      observed_yield_pct: lot.yield,
      baseline_yield_pct: null,
      yield_drop_pp: null,
      message: "No comparable lots available for baseline.",
      comparison_count: 0,
      references: []
    };
  }

  // Median baseline
  const yields = references.map((r) => r.yield).sort((a, b) => a - b);
  const mid = Math.floor(yields.length / 2);
  const baseline = yields.length % 2 !== 0 ? yields[mid] : (yields[mid - 1] + yields[mid]) / 2;
  const yieldDrop = Number((baseline - lot.yield).toFixed(2));
  const isAnomaly = yieldDrop >= minDropPp;

  return {
    lot_id: lot.lot_id,
    product_id: lot.product_id,
    status: isAnomaly ? "ALERT" : "NORMAL",
    observed_yield_pct: lot.yield,
    baseline_yield_pct: Number(baseline.toFixed(2)),
    yield_drop_pp: yieldDrop,
    threshold_pp: minDropPp,
    comparison_count: references.length,
    references: references.map((r) => ({
      lot_id: r.lot_id,
      yield: r.yield,
      equipment_id: r.equipment_id,
      recipe_revision: r.recipe_revision
    })),
    message: isAnomaly
      ? `Yield dropped ${yieldDrop} percentage points below comparison median (threshold: ${minDropPp} pp).`
      : `Yield is within nominal variation (${yieldDrop >= 0 ? "+" : ""}${yieldDrop} pp vs baseline).`
  };
}
